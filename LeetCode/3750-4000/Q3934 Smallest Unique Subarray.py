from collections import defaultdict
from typing import List


class Solution:
    def smallestUniqueSubarray(self, nums: List[int]) -> int:
        n = len(nums)
        base = 1315423911
        mod = 10 ** 9 + 7

        def getSubarrayHashes(size):
            highest_pow = pow(base, size - 1, mod)

            current_hash = 0
            for i in range(size):
                current_hash = (current_hash * base + nums[i]) % mod

            hashes = defaultdict(int)
            hashes[current_hash] += 1

            for i in range(n - size):
                current_hash = (current_hash - nums[i] * highest_pow) % mod
                current_hash = (current_hash * base + nums[i + size]) % mod
                hashes[current_hash] += 1

            return hashes

        def isUnique(size):
            counter = getSubarrayHashes(size)
            for count in counter.values():
                if count == 1:
                    return True
            return False

        res = 0
        low, high = 1, n
        while low <= high:
            mid = (low + high) // 2
            if isUnique(mid):
                res = mid
                high = mid - 1
            else:
                low = mid + 1
        return res


