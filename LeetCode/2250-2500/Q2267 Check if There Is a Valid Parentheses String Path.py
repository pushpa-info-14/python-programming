from functools import cache


class Solution:
    def hasValidPath(self, grid: list[list[str]]) -> bool:
        m = len(grid)
        n = len(grid[0])

        if (m + n - 1) % 2 == 1 or grid[0][0] == ')' or grid[m - 1][n - 1] == '(':
            return False

        directions = [[0, 1], [1, 0]]

        @cache
        def dfs(r, c, count):
            count += 1 if grid[r][c] == '(' else -1
            if count < 0:
                return False
            if r == m - 1 and c == n - 1:
                return count == 0
            for dr, dc in directions:
                nr = r + dr
                nc = c + dc
                if nr < 0 or nr == m or nc < 0 or nc == n:
                    continue
                if dfs(nr, nc, count):
                    return True
            return False

        return dfs(0, 0, 0)


